package statutory

import (
	"embed"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
	"sync"
)

//go:embed schema.json
var schemaFS embed.FS

// Schema is the JSON Schema the filing document conforms to.
//
// It is embedded and shipped with the code rather than kept beside it, because a
// schema that can drift from the emitter is a schema that will: the test suite
// validates the emitted document against this one every time it runs.
var Schema = func() string {
	held, err := schemaFS.ReadFile("schema.json")
	if err != nil {
		panic("statutory: the embedded schema is missing: " + err.Error())
	}

	return string(held)
}()

// JSON renders the filing as the document a filing channel is handed.
//
// The output is validated before it is rendered: a document that does not hold
// up as a filing is not handed to anybody.
func (o Output) JSON() ([]byte, error) {
	if err := o.Validate(); err != nil {
		return nil, err
	}

	document, err := json.MarshalIndent(o, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("statutory: render the filing: %w", err)
	}

	if err := ValidateJSON(document); err != nil {
		return nil, err
	}

	return append(document, '\n'), nil
}

// ValidateJSON reports whether a document is a filing this package could have
// written: the shape the schema prescribes, which a document carrying an
// unresolved line does not have.
func ValidateJSON(document []byte) error {
	var held any
	if err := json.Unmarshal(document, &held); err != nil {
		return fmt.Errorf("statutory: the document is not JSON: %w", err)
	}

	compiled, err := compiledSchema()
	if err != nil {
		return err
	}

	return compiled.validate(held, compiled.root, "$")
}

// jsonSchema is the subset of JSON Schema this package's document needs, and
// nothing more: the schema that guards the filing uses `$ref`, `type`,
// `required`, `properties`, `additionalProperties`, `items`, `enum`,
// `minLength`, `minItems`, `pattern` and `minimum`.
//
// A subset is enough because the document is generated by this package and the
// schema is written for it. What is not here is not a claim that the rest of
// JSON Schema does not matter; it is a claim that a validator nobody can read is
// worse than one that says exactly what it checks.
type jsonSchema struct {
	root map[string]any
	defs map[string]any
}

// compiledSchema parses the embedded schema once.
var compiledSchema = sync.OnceValues(func() (*jsonSchema, error) {
	var doc map[string]any
	if err := json.Unmarshal([]byte(Schema), &doc); err != nil {
		return nil, fmt.Errorf("statutory: the embedded schema is not JSON: %w", err)
	}

	defs, _ := doc["$defs"].(map[string]any)

	return &jsonSchema{root: doc, defs: defs}, nil
})

// validate checks one value against one schema node.
func (s *jsonSchema) validate(value any, node map[string]any, path string) error {
	if ref, ok := node["$ref"].(string); ok {
		// A `$ref` alongside other keywords would silently drop them, which is a
		// schema that does not say what it looks like it says. This validator
		// refuses to guess.
		if len(node) > 1 {
			return fmt.Errorf("statutory: the schema's %s carries $ref %q beside other keywords, which this validator would ignore", path, ref)
		}

		target, err := s.resolve(ref)
		if err != nil {
			return err
		}

		return s.validate(value, target, path)
	}

	if want, ok := node["type"].(string); ok && !isType(value, want) {
		return fmt.Errorf("statutory: %s is %s, and the schema says %s", path, kindOf(value), want)
	}

	if allowed, ok := node["enum"].([]any); ok {
		found := false

		for _, one := range allowed {
			if one == value {
				found = true

				break
			}
		}

		if !found {
			return fmt.Errorf("statutory: %s is %v, which the schema does not allow", path, value)
		}
	}

	switch held := value.(type) {
	case map[string]any:
		return s.validateObject(held, node, path)
	case []any:
		if len(held) == 0 {
			if min, ok := numberOf(node["minItems"]); ok && min > 0 {
				return fmt.Errorf("statutory: %s holds nothing, and the schema asks for at least %d", path, min)
			}
		}

		if items, ok := node["items"].(map[string]any); ok {
			for i, item := range held {
				if err := s.validate(item, items, fmt.Sprintf("%s[%d]", path, i)); err != nil {
					return err
				}
			}
		}
	case string:
		if min, ok := numberOf(node["minLength"]); ok && len(held) < min {
			return fmt.Errorf("statutory: %s is empty, and the schema asks for at least %d characters", path, min)
		}

		if pattern, ok := node["pattern"].(string); ok {
			matched, err := regexp.MatchString(pattern, held)
			if err != nil {
				return fmt.Errorf("statutory: the schema's pattern for %s is not a pattern: %w", path, err)
			}
			if !matched {
				return fmt.Errorf("statutory: %s is %q, which does not match %s", path, held, pattern)
			}
		}
	case float64:
		if min, ok := node["minimum"].(float64); ok && held < min {
			return fmt.Errorf("statutory: %s is %v, below the schema's minimum of %v", path, held, min)
		}
	}

	return nil
}

// validateObject checks an object's required keys, its known keys, and the keys
// it may not carry.
func (s *jsonSchema) validateObject(held map[string]any, node map[string]any, path string) error {
	if required, ok := node["required"].([]any); ok {
		for _, key := range required {
			name, _ := key.(string)
			if _, present := held[name]; !present {
				return fmt.Errorf("statutory: %s has no %q", path, name)
			}
		}
	}

	properties, _ := node["properties"].(map[string]any)

	for name, value := range held {
		property, known := properties[name]
		if !known {
			if allow, ok := node["additionalProperties"].(bool); ok && !allow {
				return fmt.Errorf("statutory: %s carries %q, which the schema does not describe", path, name)
			}

			continue
		}

		sub, ok := property.(map[string]any)
		if !ok {
			continue
		}

		if err := s.validate(value, sub, path+"."+name); err != nil {
			return err
		}
	}

	return nil
}

// resolve follows a local reference.
func (s *jsonSchema) resolve(ref string) (map[string]any, error) {
	name, found := strings.CutPrefix(ref, "#/$defs/")
	if !found {
		return nil, fmt.Errorf("statutory: the schema references %q, which this validator cannot follow", ref)
	}

	target, known := s.defs[name].(map[string]any)
	if !known {
		return nil, fmt.Errorf("statutory: the schema references %q, which it does not define", ref)
	}

	return target, nil
}

// isType reports whether a decoded JSON value is of a schema type.
func isType(value any, want string) bool {
	switch want {
	case "object":
		_, ok := value.(map[string]any)
		return ok
	case "array":
		_, ok := value.([]any)
		return ok
	case "string":
		_, ok := value.(string)
		return ok
	case "boolean":
		_, ok := value.(bool)
		return ok
	case "number":
		_, ok := value.(float64)
		return ok
	case "integer":
		number, ok := value.(float64)
		return ok && number == float64(int64(number))
	case "null":
		return value == nil
	}

	return false
}

// kindOf names what a decoded JSON value is, for an error a reader can act on.
func kindOf(value any) string {
	switch held := value.(type) {
	case nil:
		return "null"
	case map[string]any:
		return "an object"
	case []any:
		return "an array"
	case string:
		return fmt.Sprintf("the string %q", held)
	case bool:
		return fmt.Sprintf("%v", held)
	case float64:
		return fmt.Sprintf("the number %v", held)
	}

	return "something else"
}

// numberOf reads a non-negative whole number out of a decoded schema.
func numberOf(value any) (int, bool) {
	number, ok := value.(float64)
	if !ok || number < 0 {
		return 0, false
	}

	return int(number), true
}
